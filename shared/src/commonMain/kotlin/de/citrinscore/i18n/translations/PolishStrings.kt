    /** Polish nouns take one form for 1, another for 2–4 (but not 12–14) and a third for everything else. */
    private fun plural(count: Int, one: String, few: String, many: String) = "$count " + when {
        count == 1 -> one
        count % 10 in 2..4 && count % 100 !in 12..14 -> few
        else -> many
    }
